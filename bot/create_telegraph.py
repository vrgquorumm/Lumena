    token = get_token()
    print("Создаём Часть 1...")
    url1 = create_page(token,
        "Лумена — О проекте, Правила и Команды (1/2)", PAGE1)
    print(f"  ✅ Часть 1: {url1}")

    # Вставляем ссылку на Часть 1 в начало Часть 2
    for node in PAGE2:
        if node.get("tag") == "p":
            for child in node.get("children", []):
                if isinstance(child, dict) and child.get("tag") == "a":
                    if "PART1_URL" in child.get("attrs", {}).get("href", ""):
                        child["attrs"]["href"] = url1

    print("Создаём Часть 2...")
    url2 = create_page(token,
        "Лумена — ИИ, Советы, FAQ и Контакты (2/2)", PAGE2)
    print(f"  ✅ Часть 2: {url2}")

    with open("telegraph_url.txt", "w") as f:
        f.write(f"Part 1: {url1}\nPart 2: {url2}\n")

    print(f"\n🔗 Часть 1: {url1}")
    print(f"🔗 Часть 2: {url2}")
    return url1, url2


