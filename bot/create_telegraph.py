def get_token():
    f = "telegraph_token.txt"
    if os.path.exists(f):
        t = open(f).read().strip()
        if t:
            return t
    acc = post("https://api.telegra.ph/createAccount", {
        "short_name": "LumenaBot", "author_name": "Hydra",
        "author_url": "https://t.me/lmnfff",
    })
    t = acc["result"]["access_token"]
    open(f, "w").write(t)
    return t


def create_page(token, title, content, author_url="https://t.me/lmnfff"):
    r = post("https://api.telegra.ph/createPage", {
        "access_token": token, "title": title,
        "author_name": "Hydra", "author_url": author_url,
        "content": content, "return_content": False,
    })
    if not r.get("ok"):
        raise RuntimeError(json.dumps(r, ensure_ascii=False))
    return r["result"]["url"]


