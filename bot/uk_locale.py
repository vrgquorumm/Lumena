def resolve_command_alias(command: str) -> str:
    """Повертає технічну назву української команди, якщо вона є."""
    normalized = (command or "").strip().casefold()
    return UK_COMMAND_ALIASES.get(normalized, normalized)


def localize_text(text: str | None) -> str | None:
    if not text:
        return text
    protected: list[str] = []

    def protect(match: re.Match) -> str:
        protected.append(match.group(0))
        return f"\x00UK{len(protected) - 1}\x00"

    # URL не перекладаємо, щоб не зламати посилання. HTML-теги та команди
    # всередині <code> безпечні для словникової заміни: aliases мають бути
    # видимими користувачу в головному чаті.
    result = re.sub(
        r"https?://\S+",
        protect,
        text,
        flags=re.IGNORECASE,
    )
    result = _PHRASE_RE.sub(_replace_phrase, result)

    def replace_word(match: re.Match) -> str:
        source = match.group(0)
        target = next(
            value for key, value in _WORDS.items()
            if key.casefold() == source.casefold()
        )
        return _case_like(source, target)

    result = _WORD_RE.sub(replace_word, result)
    for index, value in enumerate(protected):
        result = result.replace(f"\x00UK{index}\x00", value)
    return result


def localize_markup(markup):
    if markup is None or not hasattr(markup, "model_copy"):
        return markup
    rows = getattr(markup, "inline_keyboard", None)
    field_name = "inline_keyboard"
    if rows is None:
        rows = getattr(markup, "keyboard", None)
        field_name = "keyboard"
    if rows is None:
        return markup
    localized_rows = []
    for row in rows:
        localized_row = []
        for button in row:
            if not hasattr(button, "model_copy"):
                localized_row.append(button)
                continue
            label = getattr(button, "text", None)
            translated = localize_text(label) if label else label
            localized_row.append(
                button.model_copy(update={"text": translated})
                if translated != label else button
            )
        localized_rows.append(localized_row)
    return markup.model_copy(update={field_name: localized_rows})