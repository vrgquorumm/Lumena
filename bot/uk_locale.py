def _case_like(source: str, target: str) -> str:
    if source.isupper():
        return target.upper()
    if source[:1].isupper():
        return target[:1].upper() + target[1:]
    return target


def _replace_phrase(match: re.Match) -> str:
    source = match.group(0)
    target = next(
        value for key, value in _PHRASES.items()
        if key.casefold() == source.casefold()
    )
    return _case_like(source, target)


_PHRASE_RE = re.compile(
    "|".join(re.escape(key) for key in sorted(_PHRASES, key=len, reverse=True)),
    flags=re.IGNORECASE,
)
_WORD_RE = re.compile(
    r"(?<![\wА-Яа-яЁёІіЇїЄє])("
    + "|".join(re.escape(key) for key in sorted(_WORDS, key=len, reverse=True))
    + r")(?![\wА-Яа-яЁёІіЇїЄє])",
    flags=re.IGNORECASE,
)


