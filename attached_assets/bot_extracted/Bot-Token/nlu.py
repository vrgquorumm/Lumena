def stem(word: str) -> str:
    """Суффиксный стеммер для русского языка."""
    w = word.lower()
    if len(w) <= 4:
        return w
    for sfx in _SUFFIXES:
        if w.endswith(sfx):
            root_len = len(w) - len(sfx)
            if root_len >= 3:
                return w[:root_len]
    return w


