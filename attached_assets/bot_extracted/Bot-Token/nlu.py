# FUZZY LOOKUP В FACTS_DB
# ════════════════════════════════════════════════════════
def fuzzy_lookup(keywords: list[str],
                 facts_db: dict,
                 threshold: float = 0.80) -> tuple[Optional[str], float]:
    """
    Ищет факт в FACTS_DB по набору ключевых слов.
    Стратегии (в порядке приоритета):
      1. Синоним → прямой ключ
      2. Прямое совпадение
      3. Нечёткое совпадение (difflib)
    Возвращает (текст_факта, уверенность) или (None, 0.0).
    """
    best_key:   Optional[str] = None
    best_score: float         = 0.0

    db_keys = list(facts_db.keys())   # кэшируем список

    for kw in keywords:
        # 1. Синоним
        canonical = SYNONYMS.get(kw)
        if canonical and canonical in facts_db:
            return facts_db[canonical], 1.0

        # 2. Прямое совпадение
        if kw in facts_db:
            return facts_db[kw], 1.0

        # 3. Fuzzy
        if len(kw) < 3:
            continue
        for db_key in db_keys:
            # Пропускаем если длины слишком разные
            max_len = max(len(kw), len(db_key))
            if abs(len(kw) - len(db_key)) > max_len * 0.55:
                continue
            score = difflib.SequenceMatcher(None, kw, db_key).ratio()
            if score > best_score:
                best_score = score
                if score >= threshold:
                    best_key = db_key

    if best_key and best_score >= threshold:
        return facts_db[best_key], best_score
    return None, 0.0


