# ИЗВЛЕЧЕНИЕ КЛЮЧЕВЫХ СЛОВ
# ════════════════════════════════════════════════════════
def extract_keywords(text: str) -> list[str]:
    """
    Извлекает значимые слова из текста.
    Включает: оригинал, стемм, синоним.
    Исключает стоп-слова и короткие токены.
    """
    raw = re.findall(r'[а-яёa-z]{3,}', text.lower())
    result: list[str] = []
    seen: set[str] = set()

    def _add(w: str):
        if w and w not in seen and w not in STOP and len(w) >= 3:
            result.append(w)
            seen.add(w)

    for w in raw:
        if w in STOP:
            continue
        _add(w)
        s = stem(w)
        if s != w:
            _add(s)
        syn = SYNONYMS.get(w)
        if syn:
            _add(syn)
            # Синоним тоже стеммим
            _add(stem(syn))

    return result


