def _topic_react(tl_text: str, recent: list) -> Optional[str]:
    """Проверяет текст на темы и возвращает короткую живую реакцию."""
    for key, pool in _TOPIC_REACTIONS.items():
        if key in tl_text:
            fresh = [r for r in pool if r not in recent]
            return random.choice(fresh if fresh else pool)
    return None


def build_response(nlu_result: dict,
                   name: Optional[str] = None,
                   recent_bot: Optional[list] = None) -> Optional[str]:
    """
    Строит живой человеческий ответ без AI API.
    Коротко, по делу, без шаблонов — как реальный человек в чате.
    """
    intent   = nlu_result['intent']
    fact     = nlu_result.get('fact')
    conf     = nlu_result.get('confidence', 0.0)
    raw_text = nlu_result.get('raw_text', '')
    recent   = recent_bot or []

    def _pick(pool: list) -> str:
        fresh = [r for r in pool if r not in recent]
        return random.choice(fresh if fresh else pool)

    def _name(text: str, prob: float = 0.12) -> str:
        if name and random.random() < prob and text:
            return f"{name}, {text[0].lower()}{text[1:]}"
        return text

    # ── 1. Фиксированные интенты ──────────────────────────
    if intent == 'self':
        return _pick(_SELF_REPLIES)

    if intent == 'gratitude':
        return _pick(_GRATITUDE_REPLIES)

    if intent == 'apology':
        return _pick(_APOLOGY_REPLIES)

    if intent == 'joke':
        return _pick(_JOKE_REPLIES)

    if intent == 'boredom':
        return _name(_pick(_BOREDOM_REPLIES), 0.15)

    if intent == 'farewell':
        return _pick(_FAREWELL_REPLIES)

    if intent == 'greeting':
        return _pick(_GREETING_REPLIES)

    if intent == 'negative':
        return _name(_pick(_NEGATIVE_REPLIES), 0.20)

    if intent == 'positive':
        return _name(_pick(_POSITIVE_REPLIES), 0.15)

    # ── 2. Факт с хорошей уверенностью ───────────────────
    if fact and conf >= 0.75:
        intro = _pick(_FACT_INTROS)
        return _name(intro + fact, 0.10)

    # ── 3. Тематические реакции (по тексту) ──────────────
    if raw_text:
        topic_reply = _topic_react(raw_text, recent)
        if topic_reply:
            return topic_reply

    # ── 4. Вопрос без факта → честный ответ ──────────────
    if intent == 'question':
        return _pick(_QUESTION_NO_FACT)

    # ── 5. Всё остальное ─────────────────────────────────
    return _pick(_CHAT_REPLIES)
