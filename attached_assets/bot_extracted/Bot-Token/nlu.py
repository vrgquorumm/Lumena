# ГЛАВНАЯ ФУНКЦИЯ ПОНИМАНИЯ
# ════════════════════════════════════════════════════════
_REF_RE = re.compile(
    r'\b(него|неё|этого|этой|этому|этим|про\s+него|про\s+неё|про\s+это|'
    r'об\s+этом|в\s+этом|на\s+эту|в\s+эту|насчёт\s+него)\b',
    re.I
)

def understand(text: str, history: list, facts_db: dict) -> dict:
    """
    Главная функция NLU. Возвращает словарь:
    {
      'intent'    : str,        # тип намерения
      'keywords'  : list[str],  # ключевые слова
      'fact'      : str|None,   # найденный факт
      'confidence': float,      # уверенность 0–1
      'topic'     : str|None,   # тема (для вывода в ответе)
      'sentiment' : str,        # positive / negative / neutral
    }
    """
    keywords   = extract_keywords(text)
    intent     = detect_intent(text)
    fact, conf = fuzzy_lookup(keywords, facts_db)

    # Тема — первое keyword совпавшее с базой
    topic: Optional[str] = None
    for kw in keywords:
        resolved = SYNONYMS.get(kw, kw)
        if resolved in facts_db or kw in facts_db:
            topic = resolved if resolved in facts_db else kw
            break

    # Если есть местоимённая ссылка — смотрим в историю
    if (not fact or not topic) and _REF_RE.search(text):
        for role, prev_text in reversed(history[-8:]):
            if role != 'user':
                continue
            prev_kw = extract_keywords(prev_text)
            prev_fact, prev_conf = fuzzy_lookup(prev_kw, facts_db, threshold=0.75)
            if prev_fact:
                fact  = prev_fact
                conf  = prev_conf * 0.85
                for pk in prev_kw:
                    res = SYNONYMS.get(pk, pk)
                    if res in facts_db or pk in facts_db:
                        topic = res if res in facts_db else pk
                        break
                break

    sentiment = ('negative' if intent == 'negative'
                 else 'positive' if intent == 'positive'
                 else 'neutral')

    return {
        'intent':     intent,
        'keywords':   keywords,
        'fact':       fact,
        'confidence': conf,
        'topic':      topic,
        'sentiment':  sentiment,
        'raw_text':   text.lower(),
    }


